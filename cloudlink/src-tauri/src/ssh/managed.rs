    #[test]
    fn add_include_backs_up_and_keeps_the_rest() {
        let dir = tempfile::tempdir().unwrap();
        let cfg = dir.path().join("config");
        let original = "\u{feff}Host mine\r\n  HostName 10.0.0.1\r\n";
        fs::write(&cfg, original).unwrap();
        let backup = add_include(&cfg).unwrap().unwrap();
        assert_eq!(backup.file_name().unwrap(), "config.cloudlink-bak");
        assert_eq!(fs::read_to_string(&backup).unwrap(), original);
        let now = fs::read_to_string(&cfg).unwrap();
        assert_eq!(
            now,
            format!("\u{feff}{INCLUDE_LINE}\r\n\r\nHost mine\r\n  HostName 10.0.0.1\r\n")
        );
        assert!(add_include(&cfg).unwrap().is_none(), "second call is a no-op");

        // 新建：没有原文件就不需要备份
        let fresh = dir.path().join("fresh").join("config");
        assert!(add_include(&fresh).unwrap().is_none());
        assert_eq!(fs::read_to_string(&fresh).unwrap(), format!("{INCLUDE_LINE}\n"));

        // 已有备份时不覆盖
        fs::write(&cfg, "Host other\n").unwrap();
        let b2 = add_include(&cfg).unwrap().unwrap();
        assert_eq!(b2.file_name().unwrap(), "config.cloudlink-bak-2");
        assert_eq!(fs::read_to_string(&backup).unwrap(), original);
    }

