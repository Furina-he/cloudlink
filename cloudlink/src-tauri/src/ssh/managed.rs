//! 托管 ssh 配置（F-107）：CloudLink 只整文件重写自己的 `~/.ssh/cloudlink.conf`，
//! 在用户 `~/.ssh/config` 开头加一行 Include（征得同意、先备份），除此之外不碰用户 config 的任何内容。

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use super::validate::{alias_ok, host_ok, identity_ok, require, user_ok};
use crate::env::EnvContext;
use crate::error::{AppError, Result};
use crate::fsx;
use crate::model::asset::{Asset, AuthMethod, ConnectionSource};

pub const MANAGED_HEADER: &str = "# Generated by CloudLink — do not edit. CloudLink rewrites this whole file.";
pub const INCLUDE_LINE: &str = "Include ~/.ssh/cloudlink.conf";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IncludeMode {
    UserHome,
    Isolated,
}

impl IncludeMode {
    pub fn for_env(env: &EnvContext) -> Self {
        if env.isolated { Self::Isolated } else { Self::UserHome }
    }
}

/// OpenSSH expands `~` through the OS account, independently of CLOUDLINK_HOME/HOME.
pub fn include_line(managed_native: &str, mode: IncludeMode) -> Result<String> {
    if mode == IncludeMode::UserHome {
        return Ok(INCLUDE_LINE.into());
    }
    let path = fsx::ssh_path(managed_native);
    require(
        (identity_ok(&path, true) || identity_ok(&path, false)) && !path.contains(['*', '?', '[', ']']),
        "managedInclude",
    )?;
    Ok(format!("Include {}", quote_path(&path)))
}

/// 托管文件里的一台服务器，路径都是该环境的写法
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ManagedHost {
    pub alias: String,
    pub host: String,
    pub port: u16,
    pub user: String,
    pub method: AuthMethod,
    pub identity_file: Option<String>,
    pub proxy_jump: Option<String>,
}

impl ManagedHost {
    pub fn validate(&self, windows: bool) -> Result<()> {
        require(alias_ok(&self.alias), "sshAlias")?;
        require(host_ok(&self.host), "host")?;
        require(self.port != 0, "port")?;
        require(user_ok(&self.user), "user")?;
        if let Some(f) = &self.identity_file {
            require(identity_ok(f, windows), "identityFile")?;
        }
        if let Some(j) = &self.proxy_jump {
            require(alias_ok(j), "proxyJump")?;
        }
        Ok(())
    }

    /// 某个环境里这台 managed 服务器的写法；没有选择写入这个环境（F-107 AC5）时为 None
    pub fn from_asset(asset: &Asset, env: &EnvContext) -> Option<ManagedHost> {
        let a = asset.as_server()?;
        let c = &a.connection;
        if c.source != ConnectionSource::Managed || !c.defined_in.contains(&env.id) {
            return None;
        }
        let auth = c.auth.as_ref()?;
        Some(ManagedHost {
            alias: c.ssh_alias.clone(),
            host: c.host.clone()?,
            port: c.port.unwrap_or(22),
            user: c.user.clone()?,
            method: auth.method,
            identity_file: match auth.method {
                AuthMethod::Key => auth.identity_file.get(&env.id).cloned(),
                _ => None,
            },
            proxy_jump: c.proxy_jump.clone().flatten(),
        })
    }
}

/// 引号内的路径：Windows 写法统一成正斜杠（OpenSSH 会把 `\` 当转义符）
pub fn quote_path(p: &str) -> String {
    format!("\"{}\"", fsx::ssh_path(p))
}

/// 一个 Host 块。HostKeyAlias 固定为别名，非默认端口下 known_hosts 的记录也对得上（CC-SWITCH 3.2.4）
pub fn render_host(h: &ManagedHost, extra: &[String]) -> String {
    let mut lines = vec![
        format!("Host {}", h.alias),
        format!("  HostName {}", h.host.trim_start_matches('[').trim_end_matches(']')),
        format!("  Port {}", h.port),
        format!("  User {}", h.user),
        format!("  HostKeyAlias {}", h.alias),
    ];
    if let Some(f) = &h.identity_file {
        lines.push(format!("  IdentityFile {}", quote_path(f)));
        lines.push("  IdentitiesOnly yes".into());
    }
    if let Some(j) = &h.proxy_jump {
        lines.push(format!("  ProxyJump {j}"));
    }
    lines.extend(extra.iter().map(|l| format!("  {l}")));
    lines.join("\n")
}

/// 整个托管文件：文件头 + 每台服务器一个 Host 块（只写具体别名，不写 `Host *`）
pub fn render(hosts: &[ManagedHost]) -> String {
    let mut out = format!("{MANAGED_HEADER}\n# 由 CloudLink 生成，请勿手改；改动会在下次保存时被覆盖。\n");
    for h in hosts {
        out.push('\n');
        out.push_str(&render_host(h, &[]));
        out.push('\n');
    }
    out
}

fn owned_by_cloudlink(path: &Path) -> io::Result<bool> {
    match fs::read_to_string(path) {
        Ok(s) => Ok(s.trim_start_matches('\u{feff}').starts_with(MANAGED_HEADER)),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(true),
        Err(e) => Err(e),
    }
}

/// 写入某个环境的托管文件（CloudLink 能访问的位置）。已有文件不是 CloudLink 生成的、或者是链接时拒绝
pub fn write(path: &Path, hosts: &[ManagedHost], windows: bool) -> Result<()> {
    for h in hosts {
        h.validate(windows)?;
    }
    if fsx::path_is_link(path) || !owned_by_cloudlink(path)? {
        return Err(AppError::internal(format!(
            "{} is not managed by CloudLink",
            path.display()
        )));
    }
    if windows {
        fsx::write_restricted_atomic(path, render(hosts).as_bytes())?;
    } else {
        fsx::write_atomic(path, render(hosts).as_bytes())?;
    }
    Ok(())
}

/// 托管文件里已有的别名（导入列表要排除它们，F-102 AC4）
pub fn managed_aliases(path: &Path) -> Vec<String> {
    fs::read_to_string(path)
        .map(|s| {
            super::config::scan_text(&s)
                .hosts
                .into_iter()
                .map(|h| h.alias)
                .collect()
        })
        .unwrap_or_default()
}

/// Include 只有写在第一个 Host / Match 之前才对所有 Host 生效
pub fn is_included(user_config: &str) -> bool {
    included_path(user_config, None, IncludeMode::UserHome)
}

/// With an environment context, also recognize exactly its absolute managed config path.
pub fn is_included_at(user_config: &str, managed_native: &str, mode: IncludeMode) -> bool {
    (mode != IncludeMode::Isolated || isolated_includes(user_config, managed_native).is_ok())
        && included_path(user_config, Some(managed_native), mode)
}

fn include_paths(rest: &str) -> Vec<String> {
    let mut paths = Vec::new();
    let mut word = String::new();
    let mut quoted = false;
    for c in rest.trim_start().trim_start_matches('=').trim_start().chars() {
        match c {
            '"' => quoted = !quoted,
            '#' if !quoted => break,
            c if c.is_whitespace() && !quoted => {
                if !word.is_empty() {
                    paths.push(std::mem::take(&mut word));
                }
            }
            _ => word.push(c),
        }
    }
    if quoted {
        return Vec::new();
    }
    if !word.is_empty() {
        paths.push(word);
    }
    paths
}

fn same_include_path(path: &str, expected: &str) -> bool {
    let path = fsx::ssh_path(path);
    let expected = fsx::ssh_path(expected);
    if expected.starts_with("//") || expected.as_bytes().get(1) == Some(&b':') {
        path.eq_ignore_ascii_case(&expected)
    } else {
        path == expected
    }
}

fn include_rest(line: &str) -> Option<&str> {
    let line = line.trim().trim_start_matches('\u{feff}');
    let (key, rest) = line
        .split_once(|c: char| c.is_whitespace() || c == '=')
        .unwrap_or((line, ""));
    key.eq_ignore_ascii_case("include").then_some(rest)
}

/// Isolated fixtures only include their own managed file. Check every block, not only global lines.
fn isolated_includes(text: &str, managed_native: &str) -> Result<bool> {
    include_line(managed_native, IncludeMode::Isolated)?;
    let mut found = false;
    for rest in text.lines().filter_map(include_rest) {
        let paths = include_paths(rest);
        if paths.is_empty() || paths.iter().any(|path| !same_include_path(path, managed_native)) {
            return Err(AppError::internal(
                "isolated ssh config must use its absolute managed Include",
            ));
        }
        found = true;
    }
    Ok(found)
}

/// Validate before native SSH parses any config. Never follow a legacy relative Include into the OS profile.
pub(crate) fn check_isolated_config(env: &EnvContext, config_native: &str) -> Result<()> {
    if !env.isolated {
        return Ok(());
    }
    let read = |path: &Path| -> Result<String> {
        crate::paths::validate_file(path)?;
        match fs::read_to_string(path) {
            Ok(text) => Ok(text),
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(String::new()),
            Err(error) => Err(error.into()),
        }
    };
    let text = read(&env.to_host(config_native))?;
    if isolated_includes(&text, &env.managed_config_native())? {
        let managed = read(&env.host_in_home(&[".ssh", "cloudlink.conf"]))?;
        if managed.lines().any(|line| include_rest(line).is_some()) {
            return Err(AppError::internal(
                "isolated managed ssh config must not contain nested Includes",
            ));
        }
    }
    Ok(())
}

fn included_path(user_config: &str, managed_native: Option<&str>, mode: IncludeMode) -> bool {
    let expected = managed_native.map(fsx::ssh_path);
    for line in user_config.lines() {
        let t = line.trim().trim_start_matches('\u{feff}');
        let (key, rest) = t.split_once(|c: char| c.is_whitespace() || c == '=').unwrap_or((t, ""));
        if key.eq_ignore_ascii_case("host") || key.eq_ignore_ascii_case("match") {
            return false;
        }
        if key.eq_ignore_ascii_case("include")
            && include_paths(rest).iter().any(|path| {
                let path = fsx::ssh_path(path);
                (mode == IncludeMode::UserHome && path == "~/.ssh/cloudlink.conf")
                    || expected
                        .as_ref()
                        .is_some_and(|expected| same_include_path(&path, expected))
            })
        {
            return true;
        }
    }
    false
}

/// 在开头插入 Include：保留 BOM 和原有换行风格
pub fn with_include(user_config: &str) -> String {
    with_include_line(user_config, INCLUDE_LINE, line_ending(user_config))
}

fn line_ending(text: &str) -> &str {
    if text.contains("\r\n") { "\r\n" } else { "\n" }
}

fn with_include_line(user_config: &str, line: &str, nl: &str) -> String {
    let (bom, body) = match user_config.strip_prefix('\u{feff}') {
        Some(rest) => ("\u{feff}", rest),
        None => ("", user_config),
    };
    if body.is_empty() {
        format!("{bom}{line}{nl}")
    } else {
        format!("{bom}{line}{nl}{nl}{body}")
    }
}

/// Only the exact legacy CloudLink directive may be migrated; unrelated lines remain byte-for-byte.
fn without_legacy_include(text: &str) -> String {
    let (bom, body) = text
        .strip_prefix('\u{feff}')
        .map_or(("", text), |body| ("\u{feff}", body));
    let mut out = String::from(bom);
    for line in body.split_inclusive('\n') {
        let legacy = include_rest(line).is_some_and(|rest| {
            let paths = include_paths(rest);
            paths.len() == 1 && fsx::ssh_path(&paths[0]) == "~/.ssh/cloudlink.conf"
        });
        if !legacy {
            out.push_str(line);
        }
    }
    out
}

/// 备份文件：`config.cloudlink-bak`，已存在时用 `-2`、`-3`…，不覆盖更早的备份
pub fn backup_path(user_config: &Path) -> PathBuf {
    let base = |n: u32| {
        let mut s = user_config.as_os_str().to_owned();
        s.push(if n == 1 {
            ".cloudlink-bak".to_string()
        } else {
            format!(".cloudlink-bak-{n}")
        });
        PathBuf::from(s)
    };
    (1..)
        .map(base)
        .find(|p| fs::symlink_metadata(p).is_err())
        .expect("unbounded")
}

/// F-107 AC1：加入 Include（调用方已征得同意）。已经有了就什么都不做。返回备份文件（没有改动时为 None）
pub fn add_include(user_config: &Path) -> Result<Option<PathBuf>> {
    add_include_at(
        user_config,
        &user_config.with_file_name("cloudlink.conf").to_string_lossy(),
        IncludeMode::UserHome,
    )
}

/// Same operation for a WSL file accessed through its host path: the Include uses its native path.
pub fn add_include_at(user_config: &Path, managed_native: &str, mode: IncludeMode) -> Result<Option<PathBuf>> {
    let line = include_line(managed_native, mode)?;
    if mode == IncludeMode::Isolated {
        crate::paths::validate_file(user_config)?;
    }
    if fsx::path_is_link(user_config) {
        return Err(AppError::internal(
            "user ssh config is a link; add the Include line by hand",
        ));
    }
    let current = match fs::read(user_config) {
        Ok(b) => Some(String::from_utf8(b).map_err(|_| AppError::internal("user ssh config is not UTF-8"))?),
        Err(e) if e.kind() == io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    let original = current.as_deref().unwrap_or_default();
    let text = if mode == IncludeMode::Isolated {
        without_legacy_include(original)
    } else {
        original.into()
    };
    if mode == IncludeMode::Isolated {
        isolated_includes(&text, managed_native)?;
    }
    let next = if is_included_at(&text, managed_native, mode) {
        text
    } else {
        with_include_line(&text, &line, line_ending(original))
    };
    if next == original {
        return Ok(None);
    }
    let backup = match &current {
        Some(original) => {
            let b = backup_path(user_config);
            fsx::write_atomic(&b, original.as_bytes())?;
            Some(b)
        }
        None => None,
    };
    fsx::write_atomic(user_config, next.as_bytes())?;
    Ok(backup)
}

